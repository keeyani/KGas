#!/usr/bin/env node
/* =====================================================================
   KGas site build.

   Renders src/pages/**.html into the repository root, wrapping each in
   src/layouts/page.html and substituting values from src/data/site.json.

   No dependencies. Run with:  node build.mjs
   Check without writing with: node build.mjs --check

   Design rules this enforces:
   - Business facts live once, in src/data/site.json.
   - A value starting with "TODO-" renders inside a visible placeholder
     chip automatically, so unfinished details cannot ship quietly.
   - An unknown {{token}} is a build error, not a silent blank.
   ===================================================================== */

import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(fileURLToPath(import.meta.url));
const SRC = join(ROOT, 'src');
const PAGES = join(SRC, 'pages');
const CHECK_ONLY = process.argv.includes('--check');

const site = JSON.parse(readFileSync(join(SRC, 'data', 'site.json'), 'utf8'));
const layout = readFileSync(join(SRC, 'layouts', 'page.html'), 'utf8');

const BANNER = '<!-- GENERATED by build.mjs from src/. Do not edit this file directly;\n' +
               '     edit src/pages/ or src/data/site.json and re-run `node build.mjs`. -->\n';

/* --- helpers --------------------------------------------------------- */

const isTodo = (v) => typeof v === 'string' && v.startsWith('TODO-');

/** Data values are text, never markup. Escaped on the way in, always. */
const esc = (v) => String(v)
  .replace(/&/g, '&amp;')
  .replace(/</g, '&lt;')
  .replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;');

/** A TODO value becomes a visible chip; anything else is plain escaped text. */
const chip = (v) => (isTodo(v) ? `<span class="todo">${esc(v)}</span>` : esc(v));

/** Resolve a dotted path such as "site.phone.display". */
function lookup(path, scope) {
  return path.split('.').reduce((o, k) => (o == null ? undefined : o[k]), scope);
}

/** Split a page file into its JSON front matter and its body. */
function parsePage(text, file) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/);
  if (!m) throw new Error(`${file}: missing --- JSON front matter block`);
  let meta;
  try { meta = JSON.parse(m[1]); }
  catch (e) { throw new Error(`${file}: front matter is not valid JSON — ${e.message}`); }
  for (const required of ['title', 'description', 'section']) {
    if (!meta[required]) throw new Error(`${file}: front matter is missing "${required}"`);
  }
  return { meta, body: m[2] };
}

/** Substitute {{token}} and {{raw:token}}. Unknown tokens throw. */
function render(template, scope, where) {
  return template.replace(/\{\{(raw:)?([a-zA-Z0-9_.]+)\}\}/g, (full, raw, path) => {
    const value = lookup(path, scope);
    if (value === undefined) throw new Error(`${where}: unknown token ${full}`);
    if (typeof value !== 'string') throw new Error(`${where}: token ${full} is not a string`);
    // "raw:" suppresses the TODO chip (for attributes and URLs).
    // It does NOT suppress escaping — nothing here may inject markup.
    return raw ? esc(value) : chip(value);
  });
}

function listPages(dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const p = join(dir, entry);
    if (statSync(p).isDirectory()) out.push(...listPages(p));
    else if (entry.endsWith('.html')) out.push(p);
  }
  return out;
}

/* --- per-page fragments ---------------------------------------------- */

function navHtml(root, section) {
  return site.nav.map((item) => {
    const current = item.section === section ? ' aria-current="page"' : '';
    return `        <li><a href="${root}${item.href}"${current}>${item.label}</a></li>`;
  }).join('\n');
}

const listHtml = (items, root, indent) =>
  items.map((i) => `${indent}<li><a href="${root}${i.href}">${i.label}</a></li>`).join('\n');

function breadcrumbHtml(root, trail) {
  if (!trail || !trail.length) return '';
  const items = trail.map((c, i) => {
    const last = i === trail.length - 1;
    if (last) return `      <li aria-current="page">${c.label}</li>`;
    return `      <li><a href="${root}${c.href}">${c.label}</a></li>`;
  }).join('\n');
  return `\n<nav class="breadcrumb" aria-label="Breadcrumb">\n  <div class="wrap">\n    <ol>\n${items}\n    </ol>\n  </div>\n</nav>\n`;
}

/**
 * Each entry becomes its own ld+json block. Tokens are resolved against
 * site data so structured data is single-sourced like everything else;
 * values stay raw (no placeholder chips) because this is machine-read.
 */
function jsonldHtml(blocks, scope, where) {
  if (!blocks || !blocks.length) return '';
  return '\n' + blocks.map((b) => {
    const json = JSON.stringify(b, null, 2)
      .replace(/\{\{(?:raw:)?([a-zA-Z0-9_.]+)\}\}/g, (full, path) => {
        const value = lookup(path, scope);
        if (value === undefined) throw new Error(`${where}: unknown token ${full} in jsonld`);
        return JSON.stringify(String(value)).slice(1, -1); // JSON-escape, no quotes
      });
    JSON.parse(json); // fail the build rather than emit broken structured data
    return `<script type="application/ld+json">\n${json}\n</script>`;
  }).join('\n\n') + '\n';
}

/* --- build ----------------------------------------------------------- */

let written = 0, unchanged = 0, stale = 0;
const todoKeys = new Set();

for (const file of listPages(PAGES)) {
  const rel = relative(PAGES, file).split(sep).join('/');
  const depth = rel.split('/').length - 1;
  const root = '../'.repeat(depth);

  const { meta, body } = parsePage(readFileSync(file, 'utf8'), rel);
  // Canonical URLs drop the index.html so the directory form is canonical.
  const url = rel.replace(/(^|\/)index\.html$/, '$1');
  const scope = { site, page: { ...meta, url }, root };

  const content = render(body, scope, rel);

  let html = layout
    .replace('{{content}}', () => content)
    .replace('{{nav}}', () => navHtml(root, meta.section))
    .replace('{{breadcrumb}}', () => breadcrumbHtml(root, meta.breadcrumb))
    .replace('{{jsonld}}', () => jsonldHtml(meta.jsonld, scope, rel))
    .replace('{{footerServices}}', () => listHtml(site.services, root, '          '))
    .replace('{{footerCompany}}', () => listHtml(site.company, root, '          '));

  html = render(html, scope, `${rel} (layout)`);
  html = BANNER + html;

  for (const m of html.matchAll(/TODO-[A-Z-]+/g)) todoKeys.add(m[0]);

  const out = join(ROOT, rel);
  const existing = existsSync(out) ? readFileSync(out, 'utf8') : null;

  if (existing === html) { unchanged++; continue; }

  if (CHECK_ONLY) {
    stale++;
    console.log(`  STALE  ${rel}`);
    continue;
  }

  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, html);
  written++;
  console.log(`  built  ${rel}`);
}

/* --- report ---------------------------------------------------------- */

console.log('');
if (CHECK_ONLY) {
  console.log(`  ${unchanged} up to date, ${stale} stale`);
  if (stale) {
    console.log('\n  Generated files do not match src/. Run: node build.mjs');
    process.exit(1);
  }
} else {
  console.log(`  ${written} written, ${unchanged} unchanged`);
}

if (todoKeys.size) {
  console.log(`\n  ${todoKeys.size} unresolved placeholders:`);
  console.log('    ' + [...todoKeys].sort().join('\n    '));
  console.log('\n  These must be resolved in src/data/site.json or src/pages/ before publishing.');
}
